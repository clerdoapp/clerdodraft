// Writes src/ui/fonts-bundled.css and src/core/font-catalog.json from the @fontsource packages
// listed in package.json. Only woff2 files at regular and bold, upright and italic, are used.
//   node scripts/build-fonts.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const UI_ONLY = new Set(['hanken-grotesk']);
const ALLOWED = /^(OFL|Apache|UFL|MIT|CC0)/i;
const deps = Object.keys(JSON.parse(readFileSync('package.json', 'utf8')).dependencies).filter((d) => d.startsWith('@fontsource/'));
const css = [];
const catalog = [];
for (const dep of deps.sort()) {
  const slug = dep.slice('@fontsource/'.length);
  if (UI_ONLY.has(slug)) continue;
  const dir = join('node_modules', dep);
  const meta = JSON.parse(readFileSync(join(dir, 'metadata.json'), 'utf8'));
  if (!ALLOWED.test(meta.license?.type ?? '')) throw new Error(`${slug}: licence ${meta.license?.type} is not allowed`);
  const near = (want) => [...meta.weights].sort((a, b) => Math.abs(a - want) - Math.abs(b - want))[0];
  const regular = near(400);
  const bold = near(700) === regular && meta.weights.length > 1 ? Math.max(...meta.weights) : near(700);
  const picks = [[regular, 400], [bold, 700]];
  for (const [w, as] of picks) {
    for (const italic of [false, true]) {
      const file = join(dir, `${w}${italic ? '-italic' : ''}.css`);
      if (!existsSync(file)) continue;
      const src = readFileSync(file, 'utf8');
      for (const block of src.match(/@font-face\s*{[^}]*}/g) ?? []) {
        const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
        const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
        if (!woff2) continue;
        css.push(`@font-face{font-family:'${meta.family}';font-style:${italic ? 'italic' : 'normal'};font-weight:${as};font-display:swap;src:url(../../node_modules/${dep}/files/${woff2}) format('woff2');${range ? `unicode-range:${range};` : ''}}`);
      }
    }
  }
  catalog.push({ family: meta.family, category: meta.category, subsets: meta.subsets, license: meta.license.type });
}
writeFileSync('src/ui/fonts-bundled.css', `/* Generated by scripts/build-fonts.mjs. */\n${css.join('\n')}\n`);
writeFileSync('src/core/font-catalog.json', `${JSON.stringify(catalog, null, 1)}\n`);
console.log(`${catalog.length} families, ${css.length} faces`);
